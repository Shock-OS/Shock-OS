import argparse

parser = argparse.ArgumentParser(description="A simple argument parser example")

parser.add_argument('--full-name', help="Specify the full name")
parser.add_argument('--version-number', help="Specify the version number")
parser.add_argument('--de-edition', help="Specify the edition (desktop environment)")
parser.add_argument('--build-date', help="Specify the build date")

args = parser.parse_args()

SHOCK_FULL_NAME = ""
SHOCK_VERSION_NUMBER = ""
SHOCK_DE_EDITION = ""
SHOCK_BUILD_DATE = ""

with open('/usr/share/shock/dist-info') as dist_info:
    code = dist_info.read()
    exec(code)

if args.full_name:
    SHOCK_FULL_NAME = args.full_name

if args.version_number:
    SHOCK_VERSION_NUMBER = args.version_number

if args.de_edition:
    SHOCK_DE_EDITION = args.de_edition

if args.build_date:
    SHOCK_BUILD_DATE = args.build_date

with open('/usr/share/shock/dist-info', 'w') as dist_info:
    dist_info.write(f'# DO NOT EDIT THIS FILE, DOING SO WILL CAUSE YOUR SYSTEM TO FUNCTION IMPROPERLY\n\
SHOCK_FULL_NAME="{SHOCK_FULL_NAME}"\n\
SHOCK_VERSION_NUMBER="{SHOCK_VERSION_NUMBER}"\n\
SHOCK_DE_EDITION="{SHOCK_DE_EDITION}"\n\
SHOCK_BUILD_DATE="{SHOCK_BUILD_DATE}"')
