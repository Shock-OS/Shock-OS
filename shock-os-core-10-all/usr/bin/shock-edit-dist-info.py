import argparse
import sys
sys.path.append('/usr/share/shock')
import dist_info

parser = argparse.ArgumentParser(description="A simple argument parser example")

parser.add_argument('--full-name', help="Specify the full name")
parser.add_argument('--version-number', help="Specify the version number")
parser.add_argument('--edition', help="Specify the edition (desktop environment)")
parser.add_argument('--build-date', help="Specify the build date")

args = parser.parse_args()

if args.full_name:
    full_name = args.full_name
elif dist_info.full_name:
    full_name = dist_info.full_name
else:
    full_name = ""

if args.version_number:
    version_number = args.version_number
elif dist_info.version_number:
    version_number = dist_info.version_number
else:
    version_number = ""

if args.edition:
    edition = args.edition
elif dist_info.edition:
    edition = dist_info.edition
else:
    edition = ""

if args.build_date:
    build_date = args.build_date
elif dist_info.build_date:
    build_date = dist_info.build_date
else:
    build_date = ""

with open('/usr/share/shock/dist-info', 'w') as dist_info:
    dist_info.write(f'# DO NOT EDIT THIS FILE, DOING SO WILL CAUSE YOUR SYSTEM TO FUNCTION IMPROPERLY\n\
SHOCK_FULL_NAME="{full_name}"\n\
SHOCK_VERSION_NUMBER="{version_number}"\n\
SHOCK_DE_EDITION="{edition}"\n\
SHOCK_BUILD_DATE="{build_date}"')

with open('/usr/share/shock/dist_info.py', 'w') as dist_info:
        dist_info.write(f'# DO NOT EDIT THIS FILE, DOING SO WILL CAUSE YOUR SYSTEM TO FUNCTION IMPROPERLY\n\
full_name = "{full_name}"\n\
version_number = "{version_number}"\n\
edition = "{edition}"\n\
build_date = "{build_date}"')
